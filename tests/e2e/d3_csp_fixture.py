"""Phase D3 — CSP Enforcement Browser E2E Test Fixture.

This fixture serves as an external test host environment specifically designed
to create negative conditions proving that real browsers enforce Content Security
Policy (CSP) headers generated by XSSGuard.

Endpoints:
- GET /no-nonce: Inline script without nonce attribute (must be blocked by CSP).
- GET /wrong-nonce: Inline script with an invalid/fake nonce attribute (must be blocked by CSP).

Running independently:
    python tests/e2e/d3_csp_fixture.py
Server will listen on http://127.0.0.1:5001
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Optional

# Ensure repository root is in sys.path when executed directly
repo_root = str(Path(__file__).resolve().parent.parent.parent)
if repo_root not in sys.path:
    sys.path.insert(0, repo_root)

from flask import Flask, Response
from xssguard.flask_ext import XSSGuard
from xssguard.storage import BaseStore, MemoryStore


NO_NONCE_HTML = """<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <title>D3 CSP Fixture - No Nonce</title>
</head>
<body>
    <h1>D3 CSP Fixture: No Nonce</h1>
    <p>Testing CSP enforcement against inline script without nonce attribute.</p>
    <script>
        console.log("D3_NO_NONCE_EXECUTED");
    </script>
</body>
</html>"""

WRONG_NONCE_HTML = """<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <title>D3 CSP Fixture - Wrong Nonce</title>
</head>
<body>
    <h1>D3 CSP Fixture: Wrong Nonce</h1>
    <p>Testing CSP enforcement against inline script with invalid nonce attribute.</p>
    <script nonce="invalid-test-nonce">
        console.log("D3_WRONG_NONCE_EXECUTED");
    </script>
</body>
</html>"""


def create_test_app(store: Optional[BaseStore] = None) -> Flask:
    """Create and configure the minimal Flask application wrapped with XSSGuard."""
    app = Flask(__name__)

    # Storage backend for XSSGuard (defaults to MemoryStore)
    fixture_store = store if store is not None else MemoryStore()

    # Initialize XSSGuard extension on the Flask app
    # This attaches XSSGuardMiddleware to app.wsgi_app and registers /csp-report
    guard = XSSGuard(app=app, store=fixture_store)
    app.extensions["xssguard"] = guard
    app.store = fixture_store

    @app.route("/no-nonce", methods=["GET"])
    def no_nonce() -> Response:
        """Endpoint serving inline script with NO nonce attribute."""
        return Response(NO_NONCE_HTML, mimetype="text/html")

    @app.route("/wrong-nonce", methods=["GET"])
    def wrong_nonce() -> Response:
        """Endpoint serving inline script with an INTENTIONALLY WRONG nonce."""
        return Response(WRONG_NONCE_HTML, mimetype="text/html")

    return app


if __name__ == "__main__":
    app = create_test_app()
    print("Starting D3 CSP Fixture server on http://127.0.0.1:5001 ...")
    app.run(host="127.0.0.1", port=5001, debug=False)
